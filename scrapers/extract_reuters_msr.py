def clean(s):
    return re.sub(r'[_|]+$', '', re.sub(r'\s+', ' ', s or '')).strip(' .:;,_-')


def number(s):
    """Integer from a value as printed: '10 (Ten)' -> 10, 'Zero (0) days' -> 0, 'Ø' -> 0.
    'N/A', 'NA' and 'None' mean no days or patients, so they are 0; a blank stays blank."""
    if not s:
        return None
    if s.strip() == 'Ø' or re.fullmatch(r'n/?a', s.strip().lower()):
        return 0
    m = re.search(r'\d+', s)
    if m:
        return int(m.group())
    m = re.search(r'\b(' + '|'.join(WORDS) + r')\b', s.lower())
    return WORDS[m.group(1)] if m else None


def parse(t):
    """First-pass parse of the OCR text of an MH-7711-1."""
    def after(pattern):
        m = re.search(pattern + r'[\s:;!.\'’]*([^\n]*)', t, re.I)
        return clean(m.group(1)) if m else ''

    def answer(pattern):
        m = re.search(pattern, t, re.I | re.S)
        return clean(m.group(1)) if m else ''

    r = {'institution_as_stated': after(r'Institution\s*:'),
         'memo_date_as_stated': after(r'\bDate\s*:'),
         'report_month_as_stated': after(r'for the month of'),
         'outside_90f_as_stated': answer(r'outside\s+temp\w*.*?\?\s*:?\s*([^\n]*)'),
         'cooling_measures_as_stated': answer(r'cooling\s+and.{0,120}?\?\s*([^\n]*)'),
         'medical_rounds_as_stated': answer(r'medical\s+rounds.{0,120}?\?\s*([^\n]*)'),
         'heat_risk_list_archived_as_stated': answer(r'Weekly\s+list\s+of\s+heat.{0,30}?archived\W*([^\n]*)'),
         'heat_illness_patients_as_stated': answer(r'patients with heat related\s+\w+\W*([^A-Za-z\n]*?\d+|\w+)?\s*List')}
    days = re.findall(r'Number of days Stage\s*\S{1,4}\s*Ale\w*\s*initiat\w*\s*[:;.]?\s*([^\n]*)', t, re.I)
    for k, v in zip(('stage_i_days_as_stated', 'stage_ii_days_as_stated', 'stage_iii_days_as_stated'),
                    days + [''] * 3):
        r[k] = clean(v)
    return r


def pages(pdf):
    out = subprocess.run(['pdfinfo', str(pdf)], capture_output=True, text=True, check=True).stdout
    return int(re.search(r'Pages:\s+(\d+)', out).group(1))


def ocr_page(pdf, page, dpi, psm='4'):
    with tempfile.TemporaryDirectory() as t:
        subprocess.run(['pdftoppm', '-r', str(dpi), '-gray', '-f', str(page), '-l', str(page), '-singlefile',
                        '-png', str(pdf), f'{t}/p'], check=True, capture_output=True)
        return subprocess.run(['tesseract', f'{t}/p.png', '-', '--psm', psm],
                              capture_output=True, text=True).stdout


def find_form(pdf):
    """Page holding the MH-7711-1: PAGES, else the first of pages 1–4 that looks like one."""
    if pdf.name in PAGES:
        return PAGES[pdf.name]
    key = re.compile(r'MONTHLY\s+SUMMARY|7711-1|Statewide Heat Plan|Number of days Stage', re.I)
    for p in range(1, min(4, pages(pdf)) + 1):
        if key.search(ocr_page(pdf, p, 100, '3')):
            return p
    return 1


def read(pdf):
    page = find_form(pdf)
    return pdf, page, parse(ocr_page(pdf, page, 300))


def month(stated, file):
    """YYYY-MM from the month the form states; the year is from the file name when the form gives none."""
    m = re.search(r'(' + '|'.join(MONTHS) + r')', stated.lower())
    y = re.search(r'20\d\d', stated)
    year = y.group() if y else '20' + re.search(r'_MSR_\d\d(\d\d)', file).group(1)
    return f'{year}-{MONTHS[m.group(1)]:02d}' if m else ''


def institution_codes():
    codes = {}
    with open(ROOT / 'crosswalk' / 'institutions.csv') as f:
        for r in csv.DictReader(f):
            codes[r['cdcr_code']] = r['cdcr_code']
            for alias in filter(None, r['alias_codes'].split(';')):
                codes[alias.strip()] = r['cdcr_code']
    return codes


def main():
    codes = institution_codes()
    files = sorted(p for p in PDF_DIR.glob('*.pdf') if p.name not in SKIP)
    with ThreadPoolExecutor(4) as ex:
        results = list(ex.map(read, files))
    out = []
    for pdf, page, ocr in results:
        fixed = FROM_IMAGE.get(pdf.name, {})
        vals = {k: fixed.get(k, ocr.get(k, '')) for k in FIELDS}
        stated_code = re.sub(r'\s+', '', vals['institution_as_stated']).upper()
        code = codes.get(stated_code) or codes.get(pdf.name.split('_')[0])
        out.append(dict(
            cdcr_code=code, institution_as_stated=vals['institution_as_stated'],
            month=month(vals['report_month_as_stated'], pdf.name),
            memo_date_as_stated=vals['memo_date_as_stated'],
            report_month_as_stated=vals['report_month_as_stated'],
            outside_90f_as_stated=vals['outside_90f_as_stated'],
            stage_i_days_as_stated=vals['stage_i_days_as_stated'], stage_i_days=number(vals['stage_i_days_as_stated']),
            cooling_measures_as_stated=vals['cooling_measures_as_stated'],
            stage_ii_days_as_stated=vals['stage_ii_days_as_stated'], stage_ii_days=number(vals['stage_ii_days_as_stated']),
            medical_rounds_as_stated=vals['medical_rounds_as_stated'],
            stage_iii_days_as_stated=vals['stage_iii_days_as_stated'],
            stage_iii_days=number(vals['stage_iii_days_as_stated']),
            heat_risk_list_archived_as_stated=vals['heat_risk_list_archived_as_stated'],
            heat_illness_patients_as_stated=vals['heat_illness_patients_as_stated'],
            heat_illness_patients=number(vals['heat_illness_patients_as_stated']),
            source_file=pdf.name, page=page,
            ocr_check='corrected from image' if fixed else 'ocr', note=NOTES.get(pdf.name, '')))
    # A package with no form for its own month is a gap: one row with every value blank
    for name, why in SKIP.items():
        m = re.match(r'([A-Z]+)_MSR_(\d\d)(\d\d)', name)
        out.append(dict(cdcr_code=codes.get(m.group(1)), month=f'20{m.group(3)}-{m.group(2)}',
                        source_file=name, note=why + ' No form for this month; values are blank.'))
    out.sort(key=lambda r: (r['cdcr_code'], r['month']))
    with open(OUT, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(out[0]), lineterminator='\n', restval='')
        w.writeheader()
        w.writerows(out)
    print(f'{len(out)} forms from {len(files)} packages → {OUT}')
    for name, why in SKIP.items():
        print(f'skipped {name}: {why}')


if __name__ == '__main__':
    main()
